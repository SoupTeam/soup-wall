"""Write or check scripts/README.md, the index of this directory by area.

The index lists every top-level script with the first line of its module
docstring (Python) or of its leading comment (shell and PowerShell). It reads
only file names and those first lines: nothing is imported or executed.

    python3 scripts/scripts_index.py            # rewrite scripts/README.md
    python3 scripts/scripts_index.py --check    # fail if it is out of date
"""

import argparse
import ast
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
INDEX = HERE / "README.md"
KINDS = (".py", ".sh", ".ps1", ".mjs")

# First match wins, so the order matters: a pilot qualifier is listed under the pilot.
AREAS = (
    ("Pilot", "Preparing, installing, running, qualifying and maintaining the Linux pilot.",
     lambda name: "pilot" in name),
    ("Console and identity", "Console acceptance, Keycloak, OIDC, SAML, SCIM and SSO drivers.",
     lambda name: name.startswith(("console", "keycloak", "scim", "sso", "oidc", "saml"))),
    ("Managed policy and fleet", "Managed policy rollout, credentials, groups and fleet acceptance.",
     lambda name: name.startswith(("managed", "fleet"))),
    ("MCP and native acceptance", "Drivers that run real MCP servers or the native endpoint through the Agent.",
     lambda name: name.startswith(("verify-", "verify_", "mcp", "native", "claude", "windows-", "macos-", "test-"))),
    ("Qualification", "Qualification runs that are not specific to the pilot.",
     lambda name: name.startswith(("qualify-", "qualify_"))),
    ("Profiles and installation", "Installing, staging and fetching profiles, runtimes and models.",
     lambda name: name.startswith(("install-", "stage-", "fetch-", "build-", "prepare-"))),
    ("CI, candidates and release", "CI planning and admission, candidate custody, licence and release checks.",
     lambda name: name.startswith(("ci", "local_pr", "release", "check_", "check-", "package", "supply", "candidate",
                                   "validate", "linux_candidate", "publication", "license", "generate_inventory",
                                   "runtime_reviews", "github-", "run-all-tests", "scripts_index"))),
    ("Agent setup, audit and diagnostics", "Onboarding, audit reports, doctor exports and schema upgrades.",
     lambda name: name.startswith(("agent-", "agent_", "onboarding", "clean-setup", "schema-upgrade", "diagnose",
                                   "edit-run", "roadmap"))),
    ("Operations drills", "Opt-in drills for monitoring, alerting, restore, TLS and Compose deployments.",
     lambda name: name.startswith(("alert", "monitoring", "local-", "production-", "postgres-", "staging", "tls-",
                                   "self-hosted", "linux-alert")) or name.endswith(("-drill.ps1", "-smoke.ps1"))),
    ("Other", "Everything else: demos, reports, benchmarks, diagnostics and shared modules.",
     lambda name: True),
)

DIRECTORIES = {
    "benchmarks": "Benchmark plans and runners, with their own tests.",
    "ci": "Helpers used only by CI workflows.",
    "fixtures": "Inputs for the acceptance drivers: fault-injection sources, recorded calls, test servers.",
    "roadmap_support_assets": "Static assets for the roadmap support report.",
    "sdk_compat": "The client used by the official SDK compatibility check.",
    "tests": "Unit tests for the scripts, run with `python3 -m unittest discover -s scripts/tests`.",
}

HEADER = """# Scripts

This file is generated by `scripts/scripts_index.py`. Edit that file or the
script's own first docstring line, then run `python3 scripts/scripts_index.py`.

## Conventions

- **Scripts are self-contained on purpose.** Most acceptance drivers record the
  SHA-256 of their own source, and of an explicit list of other files, in the
  evidence they produce. A helper moved into a shared module falls outside that
  record unless every list is extended. This is why small helpers such as
  `sha256` or `require` are repeated instead of imported.
- **Changing a script changes its digest.** Evidence under `docs/**/evidence/`
  records the digest a script had when it ran, and a few manifests pin the
  current one. Before editing or renaming a script, search for its path and its
  current `sha256sum` with `git grep`.
- **Ticket numbers in names are historical.** Names such as `verify-sou62-...`
  come from the ticket that introduced the script. The description column says
  what the script does.
- **Scripts are flat.** They load each other by file name from this directory,
  and workflows call them by exact path.
"""


def first_line(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix == ".py":
        try:
            documented = ast.get_docstring(ast.parse(text))
        except SyntaxError:
            documented = None
        return documented.strip().splitlines()[0].strip() if documented else ""
    for line in text.splitlines():
        line = line.strip()
        if line.startswith(("#!", "# SPDX", "// SPDX")) or not line:
            continue
        if line.startswith(("#", "//")):
            return line.lstrip("#/ ").strip()
        return ""
    return ""


def cell(text):
    return text.replace("|", "\\|")


def render():
    names = sorted(path.name for path in HERE.iterdir() if path.is_file() and path.suffix in KINDS)
    groups = {title: [] for title, _, _ in AREAS}
    for name in names:
        groups[next(title for title, _, belongs in AREAS if belongs(name))].append(name)
    parts = [HEADER, "## Subdirectories\n\n| Directory | Contents |\n| --- | --- |"]
    parts.extend("| [`%s/`](%s/) | %s |" % (name, name, cell(text)) for name, text in sorted(DIRECTORIES.items()))
    for title, summary, _ in AREAS:
        parts.append("\n## %s\n\n%s\n\n| Script | What it does |\n| --- | --- |" % (title, summary))
        parts.extend("| [`%s`](%s) | %s |" % (name, name, cell(first_line(HERE / name))) for name in groups[title])
    return "\n".join(parts) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if scripts/README.md is out of date")
    arguments = parser.parse_args()
    expected = render()
    if arguments.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != expected:
            print("scripts/README.md is out of date; run: python3 scripts/scripts_index.py", file=sys.stderr)
            return 1
        return 0
    INDEX.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
