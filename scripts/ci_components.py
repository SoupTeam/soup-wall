#!/usr/bin/env python3
"""Generate shared component qualification without changing manual job bodies.

The original manually dispatchable workflows remain the editable source of truth.
Names, planner/build dependencies and the reviewed execution mode change.
Commands, artifacts, runtime isolation and matrices stay in the source workflows.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re

from ci_impact import WORKFLOW_JOBS, BUILD_CONSUMERS, BUILD_PRODUCER

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / ".github/workflows/ci-components.yml"
HEADER = """# Generated by scripts/ci_components.py; edit the original manual workflows.
name: CI component qualification
on:
  workflow_call:
    inputs:
      plan:
        required: true
        type: string
      backend:
        type: string
        default: all
      runs:
        type: string
        default: '1'
permissions:
  contents: read
jobs:
"""


def blocks(text: str) -> dict[str, str]:
    jobs = text.split("jobs:\n", 1)[1]
    matches = list(re.finditer(r"^  ([a-z][a-z0-9-]*):\s*\n", jobs, re.M))
    return {m[1]: jobs[m.end():matches[i + 1].start() if i + 1 < len(matches) else len(jobs)]
            for i, m in enumerate(matches)}


def generated() -> str:
    output = [HEADER]
    for workflow, expected in WORKFLOW_JOBS.items():
        if workflow == "ci.yml":
            continue
        source = (ROOT / ".github/workflows" / workflow).read_text(encoding="utf-8-sig")
        jobs = blocks(source)
        # This explicitly dispatched hour-long development exercise must never
        # enter ordinary component qualification or required admission.
        manual = {"mcp-real-filesystem.yml": {"manual-long-session", "manual-native-result-profile",
                                              "manual-sou194-cache-exchange"},
                  "mcp-real-git.yml": {"manual-installed-git-profiles", "sou182-raw-boundary"},
                  "mcp-create-file.yml": {"reuse-plan", "reuse-qualification"}}.get(workflow, set())
        if set(jobs) != {*expected, "impact", *manual}:
            raise ValueError("Unregistered source jobs: " + workflow)
        prefix = workflow.removesuffix(".yml")
        for job_id in expected:
            body = jobs[job_id]
            if body.count("    needs: impact\n") != 1:
                raise ValueError("Unsupported component dependency: " + workflow)
            body = body.replace("    needs: impact\n", "", 1)
            before = "fromJSON(needs.impact.outputs.jobs || '[]')"
            if before not in body:
                raise ValueError("Missing planner condition: " + workflow)
            body = body.replace(before, "fromJSON(inputs.plan).workflows['" + workflow + "']")
            # Selected consumers report a failed producer through their own
            # explicit guard, but must not start on an obsolete cancelled run.
            # Step-level always() evidence uploads remain unchanged.
            if job_id in BUILD_CONSUMERS.get(workflow, ()):
                producer = BUILD_PRODUCER[0].removesuffix(".yml") + "--" + BUILD_PRODUCER[1]
                body = "    needs: " + producer + "\n" + body
                # A leading ! is YAML tag syntax unless the expression is
                # quoted or emitted as a block scalar.
                body = body.replace("    if: ", "    if: >-\n      !cancelled() && ", 1)
                body = body.replace(" && github.event.inputs.build_mode != 'shared'", "", 1)
                body = body.replace("      SOU166_MODE: source\n", "      SOU166_MODE: shared\n", 1)
                for key, field in {"RESULT": "result", "ATTEMPT": "outputs.producer_attempt",
                                   "IMAGE_VERSION": "outputs.image_version",
                                   "ARTIFACT_ID": "outputs.artifact_id", "ARCHIVE_NAME": "outputs.archive_name",
                                   "ARCHIVE_SHA256": "outputs.archive_sha256", "MANIFEST_SHA256": "outputs.manifest_sha256"}.items():
                    variable = "SOU166_PRODUCER_" + key if key in {"RESULT", "ATTEMPT", "IMAGE_VERSION"} else "SOU166_" + key
                    old = "      " + variable + ": ''\n"
                    if body.count(old) != 1:
                        raise ValueError("Missing reviewed build dependency output: " + variable)
                    body = body.replace(old, "      " + variable + ": ${{ needs." + producer + "." + field + " }}\n", 1)
            name = re.search(r"^    name: (.+)$", body, re.M)
            if name:
                # Source names are scalar strings, not quoted YAML here. Refuse
                # new quoting styles rather than silently changing check identity.
                value = name[1]
                if value[:1] in ("'", chr(34)):
                    raise ValueError("Quoted job name needs explicit support: " + workflow)
                body = body[:name.start()] + "    name: " + json.dumps(prefix + " / " + value) + body[name.end():]
            else:
                value = job_id
                if "    strategy:" in body:
                    matrix = re.search(r"^      matrix:\n((?:        [^\n]*\n)+)", body, re.M)
                    if matrix is None:
                        raise ValueError("Implicit matrix job name needs explicit support: " + workflow)
                    axes = re.findall(r"^        ([a-zA-Z_][a-zA-Z0-9_-]*):", matrix[1], re.M)
                    if not axes or any(axis in {"include", "exclude"} for axis in axes):
                        raise ValueError("Complex implicit matrix name needs explicit support: " + workflow)
                    value += " (" + ", ".join("${{ matrix." + axis + " }}" for axis in axes) + ")"
                body = "    name: " + json.dumps(prefix + " / " + value) + "\n" + body
            output.append("  " + prefix + "--" + job_id + ":\n" + body.rstrip() + "\n\n")
    return "".join(output)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generated()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != content:
            parser.error("Component workflow drift: run python3 scripts/ci_components.py")
    else:
        TARGET.write_text(content, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
