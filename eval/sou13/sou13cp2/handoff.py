def _strings(x):
    if isinstance(x, str):
        yield x
    elif isinstance(x, dict):
        for k, v in x.items():
            yield str(k)
            yield from _strings(v)
    elif isinstance(x, list):
        for v in x:
            yield from _strings(v)


def _word_re(s):
    return re.compile(r'(?<![A-Za-z0-9_])' + re.escape(s) + r'(?![A-Za-z0-9_])')


def test_fingerprints(fams, manifest, records):
    """Strings identifying test families/records. A string that also occurs (as a whole word) in public
    material - public records, the public catalog, the interpreter - cannot identify test and is dropped."""
    catalog = get_catalog()
    test_fams = [f for f in fams if manifest['family_split'].get(f['family_id']) == 'test']
    fp = set()
    for f in test_fams:
        fid = f['family_id']
        fp |= {fid, fid[len('fam.'):], fid.rsplit('.', 1)[1], f['alias_group_id'], manifest['family_group'][fid],
               'decl:' + fid[4:]}
        fp |= {t for _, t in f['identities']} | {s for s, _ in f['identities']} | set(f['descriptions'])
        fp |= {t['template_id'] for t in f['templates']} | {t['signature'] for t in f['templates']}
        fp |= {s for s in _strings(catalog[fid]) if len(s) >= 4}
        fp.add(sha(catalog[fid]['program']))
    for r in records:
        if r['split'] == 'test':
            fp |= {r['id'], r['hashes']['input_sha256'], r['hashes']['arguments_sha256'],
                   r['hashes']['definition_sha256'], label_row(r)['label_sha256']}
    public = '\n'.join([json.dumps([r for r in records if r['split'] != 'test'], ensure_ascii=False, sort_keys=True),
                        json.dumps({k: v for k, v in catalog.items() if k not in {f['family_id'] for f in test_fams}},
                                   ensure_ascii=False, sort_keys=True),
                        (ROOT / 'sou13cp2' / 'semantics.py').read_text(encoding='utf-8'),
                        (ROOT / 'sou13cp2' / 'compute.py').read_text(encoding='utf-8')])
    return {s for s in fp if s and not (s in public and _word_re(s).search(public))}


COMMON_WORD = re.compile(r'^[a-z]{1,8}$')


def split_strength(fingerprints):
    """(strong, weak). Weak = short plain lowercase words (e.g. an argument name such as `query`): a whole-word
    match in prose is not evidence of leakage, so weak hits are reported for human review, not as errors."""
    weak = {s for s in fingerprints if COMMON_WORD.match(s)}
    return fingerprints - weak, weak


def scan(directory, fingerprints, skip=()):
    directory = Path(directory)
    hits = {}
    if not fingerprints:
        return hits
    combined = re.compile(r'(?<![A-Za-z0-9_])(?:' + '|'.join(re.escape(s) for s in sorted(fingerprints, key=len,
                                                                                            reverse=True))
                          + r')(?![A-Za-z0-9_])')
    for p in sorted(directory.rglob('*')):
        rel = p.relative_to(directory).as_posix()
        if not p.is_file() or '__pycache__' in rel or any(rel.startswith(x) for x in skip):
            continue
        text = p.read_bytes().decode('utf-8', 'replace')
        if combined.search(text):  # then list every fingerprint present, for the report
            hits[rel] = sorted(s for s in fingerprints if s in text and _word_re(s).search(text))
    return hits


def _full_state(root):
    if not restricted.available():
        raise HandoffError('restricted materials are not available (public copy)')
    fams = families()
    manifest = json.loads((Path(root) / FULL_MANIFEST_FILE).read_text(encoding='utf-8'))
    errs = manifest_errors(manifest, fams)
    if errs:
        raise HandoffError(f'authoritative manifest invalid: {errs}')
    return fams, manifest, load_records(root, fams, manifest)


def public_fingerprint_hits(root=ROOT, weak=False):
    """Fingerprint scan of every public file of the repository (full mode only). Strong hits by default."""
    fams, manifest, records = _full_state(root)
    strong_fp, weak_fp = split_strength(test_fingerprints(fams, manifest, records))
    return scan(root, weak_fp if weak else strong_fp, skip=NON_PUBLIC)


def _jsonl(rows):
    return ''.join(json.dumps(r, sort_keys=True, ensure_ascii=False) + '\n' for r in rows)


def _write(base, rel, text, bom=False):
    p = Path(base) / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(text.encode('utf-8-sig' if bom else 'utf-8'))


def _copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir():
        shutil.copytree(src, dst)
    else:
        shutil.copy(src, dst)


def _fmt(v):
    return 'null' if v is None else str(v).lower()


